export function tr(strings: typeof es, key: keyof typeof es, vars?: Record<string, string | number>): string {
  let str = strings[key] as string;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
